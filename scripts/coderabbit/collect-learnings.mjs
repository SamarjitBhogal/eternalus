#!/usr/bin/env node
/**
 * CodeRabbit learnings log (zero dependencies; needs the GitHub CLI `gh`, signed in).
 *
 *   node scripts/coderabbit/collect-learnings.mjs   # rewrite docs/agents/coderabbit-learnings.md
 *
 * CodeRabbit stores a "learning" when someone corrects it in a PR thread and announces it in a
 * "Learnings added" block of its reply. This script reads those blocks from every comment
 * CodeRabbit posted on this repo's PRs and writes them, oldest first, into the doc, so the product
 * owner can review each one (ADR 0018, DEC-98). `.github/workflows/coderabbit-learnings.yml` runs
 * it on a schedule and opens a docs PR when the doc changed.
 *
 * Exit code 1 if a comment announces learnings but none can be read (CodeRabbit changed its
 * format), so an announced learning is never dropped without notice.
 */
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const OUT_FILE = path.join(ROOT, 'docs', 'agents', 'coderabbit-learnings.md');
const BOT = 'coderabbitai[bot]';
const MARKER = 'Learnings added';
/** Review-thread replies and PR-conversation replies: CodeRabbit answers in both. */
const ENDPOINTS = ['repos/{owner}/{repo}/pulls/comments', 'repos/{owner}/{repo}/issues/comments'];

/** Lists every comment CodeRabbit posted on this repo's PRs. */
function botComments() {
  return ENDPOINTS.flatMap((endpoint) => {
    const output = execFileSync(
      'gh',
      ['api', '--paginate', '--slurp', `${endpoint}?per_page=100`],
      {
        cwd: ROOT,
        encoding: 'utf8',
        maxBuffer: 512 * 1024 * 1024,
      },
    );
    return JSON.parse(output)
      .flat()
      .filter((comment) => comment.user?.login === BOT);
  });
}

/** Reads one `Name: value` line of a learning block. */
function field(block, name) {
  return block.match(new RegExp(`^${name}: *(.*)$`, 'm'))?.[1]?.trim() ?? '';
}

/**
 * Returns the learnings announced in one comment's "Learnings added" block; throws if the block
 * is there but holds none it can read.
 */
export function parseLearnings(comment) {
  const body = comment.body.replace(/\r\n/g, '\n');
  if (!body.includes(MARKER)) return [];
  const section = body.split(MARKER)[1].split('</details>')[0];
  const learnings = [...section.matchAll(/```\n([\s\S]*?)\n```/g)].map(([, block]) => ({
    author: field(block, 'Learnt from'),
    pr: block.match(/\bPR: *(\d+)/)?.[1] ?? '',
    file: field(block, 'File'),
    timestamp: field(block, 'Timestamp'),
    text: block.match(/^Learning: *([\s\S]*)$/m)?.[1]?.trim() ?? '',
    url: comment.html_url,
  }));
  if (learnings.length === 0 || learnings.some((learning) => !learning.text)) {
    throw new Error(`cannot read the "${MARKER}" block in ${comment.html_url}`);
  }
  return learnings;
}

/** Renders the doc; the output is stable for the same learnings, so an unchanged run is a no-op. */
export function renderDoc(learnings) {
  const sorted = [...learnings].sort(
    (a, b) => a.timestamp.localeCompare(b.timestamp) || a.url.localeCompare(b.url),
  );
  const newest = sorted.at(-1)?.timestamp.slice(0, 10) || '2026-10-30';
  const entries = sorted.map((learning) =>
    [
      `## ${learning.timestamp.slice(0, 10)} · PR #${learning.pr} · \`${learning.file}\``,
      '',
      `Learnt from \`${learning.author}\` ([comment](${learning.url})).`,
      '',
      '```text',
      learning.text,
      '```',
      '',
    ].join('\n'),
  );
  return `---
title: CodeRabbit learnings
description: Generated log of every learning CodeRabbit announced on this repo's PRs, oldest first, for the product owner to review; read it to see which review rules CodeRabbit gave itself, and ask the CodeRabbit admin to reword or delete one you disagree with.
audience: [humans]
status: active
owner: sholtzman
last-reviewed: ${newest}
tags: [agents, review, coderabbit]
related: ['docs/decisions/0018-coderabbit-runs-the-pr-review-skill.md', 'docs/agents/tool-setup.md']
---

# CodeRabbit learnings

**Purpose.** CodeRabbit stores a learning when someone corrects it in a PR thread, and the
learning changes its later reviews outside git. This log lets the product owner review each one
(ADR 0018, DEC-98). If one is wrong, ask the CodeRabbit admin to reword or delete it in the
[CodeRabbit app](https://app.coderabbit.ai/learnings); learning does not wait for this review.

Generated by \`scripts/coderabbit/collect-learnings.mjs\` (on the schedule in
\`.github/workflows/coderabbit-learnings.yml\`); do not edit it by hand. It shows each learning
as CodeRabbit first announced it. A later edit or delete in the app, a learning added there
directly, or one CodeRabbit inferred without announcing it does not show here.

${entries.join('\n') || 'No learnings yet.\n'}`;
}

function main() {
  const learnings = botComments().flatMap(parseLearnings);
  writeFileSync(OUT_FILE, renderDoc(learnings));
  process.stdout.write(
    `Wrote ${learnings.length} learning(s) to docs/agents/coderabbit-learnings.md\n`,
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
